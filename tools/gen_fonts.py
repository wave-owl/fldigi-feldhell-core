#!/usr/bin/env python3
"""Generate src/feldhell_fonts.c from fldigi 4.2.13's Hellschreiber raster fonts.

    python3 tools/gen_fonts.py /path/to/fldigi > src/feldhell_fonts.c

Reads the 15 font files src/feld/Feld*.cxx (the order of get_font_data's switch, feld.cxx
lines 532-549, and of szFeldFonts in src/feld/feldfonts.cxx) and writes their glyph rows
verbatim: 95 glyphs (ASCII 0x20-0x7E, indexed by c - ' ' exactly as get_font_data does),
14 rows of 16 bits each, bit 15 = column 0. Stdlib only.
SPDX-License-Identifier: GPL-3.0-or-later
"""

import re
import sys
from pathlib import Path

#: (file, fldigi array name, name in szFeldFonts) in fldigi's font number order
FONTS = [
    ("Feld7x7-14.cxx", "feld7x7_14", "7x7"),
    ("Feld7x7n-14.cxx", "feld7x7n_14", "7x7n"),
    ("FeldDx-14.cxx", "feldDx_14", "Dx"),
    ("FeldFat-14.cxx", "feldfat_14", "fat"),
    ("FeldHell-12.cxx", "feldhell_12", "hell"),
    ("FeldLittle-12.cxx", "feldlittle_12", "little"),
    ("FeldLo8-14.cxx", "feldlo8_14", "lo8"),
    ("FeldLow-14.cxx", "feldlow_14", "low"),
    ("FeldModern-14.cxx", "feldmodern_14", "modern"),
    ("FeldModern8-14.cxx", "feldmodern8_14", "modern8"),
    ("FeldNarr-14.cxx", "feldnarr_14", "narr"),
    ("FeldReal-14.cxx", "feldreal_14", "real"),
    ("FeldStyl-14.cxx", "feldstyl_14", "style"),
    ("FeldVert-14.cxx", "feldvert_14", "vert"),
    ("FeldWide-14.cxx", "feldwide_14", "wide"),
]
ROW = re.compile(r"^\{\s*(?:'(?:\\.|.)'|\d+)\s*,\s*\{([^}]*)\}")


def parse(path):
    rows, first, last = [], None, None
    for no, line in enumerate(path.read_text().splitlines(), 1):
        m = ROW.match(line.strip())
        if not m:
            continue
        vals = [int(v, 16) for v in m.group(1).replace(" ", "").split(",") if v]
        assert len(vals) == 14, (path, no)
        rows.append(vals)
        first = first or no
        last = no
    assert len(rows) == 95, (path, len(rows))
    return rows, first, last


def main():
    root = Path(sys.argv[1]) / "src" / "feld"
    out = ["/*",
           " * fldigi-feldhell-core: the 15 Hellschreiber raster fonts of fldigi 4.2.13, verbatim.",
           " * GENERATED by tools/gen_fonts.py from src/feld/Feld*.cxx -- do not edit.",
           " *",
           " * Copyright (C) 2026 Gerolf Ziegenhain; font data from fldigi 4.2.13 (c) 2014 David",
           " * Freese W1HKJ (struct fntchr, fontdef.h:33), adapted from gmfsk.",
           " * SPDX-License-Identifier: GPL-3.0-or-later",
           " */",
           '#include "feldhell_internal.h"',
           ""]
    for fname, arr, name in FONTS:
        rows, first, last = parse(root / fname)
        out.append(f"/* {arr} (\"{name}\"), {fname}:{first}-{last} */")
        out.append(f"static const unsigned short {arr}[95][14] = {{")
        for i, r in enumerate(rows):
            ch = chr(0x20 + i)
            label = {"\\": "backslash", "/": "slash", "*": "asterisk"}.get(ch, ch)
            out.append("    {" + ", ".join(f"0x{v:04X}" for v in r) + f"}}, /* {label} */")
        out.append("};")
        out.append("")
    out.append("/* get_font_data's font switch, feld.cxx:532-549; names of szFeldFonts, feldfonts.cxx:41-56 */")
    out.append("const feldhell_font FELDHELL_FONTS[FFELDHELL_FONT_COUNT] = {")
    for fname, arr, name in FONTS:
        out.append(f'    {{"{name}", {arr}}},')
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
